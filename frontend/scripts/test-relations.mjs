import assert from 'node:assert/strict';
import {relationCandidates as relations,relations as sparse,pruneRelations} from '../src/scene/relations.js';
const table={id:'table',box:{min:[-1,0,-2],max:[1,1,-1]}};
const cup={id:'cup',box:{min:[0,1,-1.7],max:[.2,1.2,-1.5]}};
const edges=relations([table,cup]);
assert(edges.some(e=>e.source==='cup'&&e.target==='table'&&e.relation==='on'));
assert(!edges.some(e=>e.relation==='next to'));
assert(edges.some(e=>e.source==='table'&&e.target==='cup'&&e.relation==='under'));
const front={id:'front',box:{min:[2,0,0],max:[3,1,1]}};
assert(relations([table,front]).some(e=>e.source==='front'&&e.relation==='in front of'));
assert(relations([table,front]).some(e=>e.source==='table'&&e.relation==='left of'));
assert(relations([table,front]).some(e=>e.source==='front'&&e.relation==='right of'));
assert(relations([table,front]).some(e=>e.source==='table'&&e.relation==='behind'));
const neighbor={id:'neighbor',box:{min:[1.2,0,-2],max:[2.2,1,-1]}};
assert.equal(relations([table,neighbor]).filter(e=>e.relation==='next to').length,2);
const hovering={id:'hover',box:{min:[0,1.2,-1.7],max:[.2,1.4,-1.5]}};
assert(!relations([table,hovering]).some(e=>e.relation==='on'));
assert.deepEqual(relations([table,{id:'unknown'}]),[]);
console.log('Relation geometry checks passed');
const chain=Array.from({length:8},(_,i)=>({id:String(i),name:'chair',box:{min:[i*.4,0,0],max:[i*.4+.2,.3,.2]}}));
const pruned=sparse(chain);
assert(pruned.length<=3*chain.length);
assert.equal(new Set(pruned.map(e=>[e.source,e.target].sort().join('|'))).size,pruned.length);
const lower={id:'lower',box:{min:[-1,-.1,-2],max:[1,.98,-1]}};
assert.equal(sparse([cup,table,lower]).filter(e=>e.source==='cup'&&e.relation==='on').length,1);
const transitive=pruneRelations(chain.slice(0,3),[{source:'0',target:'1',relation:'left of'},{source:'1',target:'2',relation:'left of'},{source:'0',target:'2',relation:'left of'}]);
assert(!transitive.some(e=>e.source==='0'&&e.target==='2'));
assert(!sparse([{...chain[0]},{...chain[1],box:{min:[10,0,0],max:[11,1,1]}}]).length);
console.log('Stored graph pruning checks passed');
