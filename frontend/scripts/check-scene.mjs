import {fileURLToPath} from 'node:url';
process.chdir(fileURLToPath(new URL('..',import.meta.url)));
import {chromium} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
const browser=await chromium.launch({headless:true,args:['--enable-gpu','--use-angle=d3d11']});
const page=await browser.newPage({viewport:{width:1600,height:1000}});
const errors=[],external=[];
page.on('pageerror',e=>errors.push(e.stack));
page.on('request',r=>{if(/^https?:/.test(r.url())&&!r.url().startsWith('http://127.0.0.1:5173'))external.push(r.url());});
await page.goto('http://127.0.0.1:5173/scene.html?scene=sunroom');
await page.waitForFunction(()=>document.querySelector('#viewport').dataset.loaded==='true',{},{timeout:180000});
await page.waitForTimeout(4000);
await mkdir('../docs/screenshots',{recursive:true});
await page.screenshot({timeout:120000,path:'../docs/screenshots/stage1-original.png'});
const state=await page.evaluate(()=>{const v=window.sceneWorkspace;return {position:v.camera.position.toArray(),target:v.controls.target.toArray(),splatCount:v.splat.packedSplats.numSplats,originalSize:[v.manifest.camera.width,v.manifest.camera.height]};});
const canvas=page.locator('canvas');const bounds=await canvas.boundingBox();
await page.mouse.move(bounds.x+bounds.width*.5,bounds.y+bounds.height*.5);
await page.mouse.down();await page.mouse.move(bounds.x+bounds.width*.8,bounds.y+bounds.height*.5,{steps:20});await page.mouse.up();
await page.waitForTimeout(1200);
await page.screenshot({timeout:120000,path:'../docs/screenshots/stage1-orbit.png'});
const angle=await page.evaluate(()=>window.sceneWorkspace.controls.getAzimuthalAngle());
await page.getByRole('button',{name:'원본 시점',exact:true}).click();
await page.waitForTimeout(1000);
await writeFile('../docs/scene-browser-check.json',JSON.stringify({errors,external,state,orbitRadians:angle},null,2));
await browser.close();
if(errors.length||external.length||Math.abs(angle)>8*Math.PI/180+.001)throw Error(JSON.stringify({errors,external,angle}));
console.log(JSON.stringify({errors,external,state,orbitRadians:angle}));
